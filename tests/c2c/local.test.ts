import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { localAccess } from "../../src/c2c/local.js";
import { Workspace } from "../../src/workspace/manager.js";
import { cleanup, git, isolateStateDir, makeGitRepo, makeTmpDir } from "../helpers.js";

let state: string, root: string, workspaceId: string;
beforeEach(() => {
  state = isolateStateDir(); root = makeTmpDir("c2c-local"); makeGitRepo(root);
  workspaceId = new Workspace(root).id;
});
afterEach(() => {
  vi.restoreAllMocks(); cleanup(root); cleanup(state); delete process.env.C2C_STATE_DIR;
});
const fingerprint = () => localAccess.sourceFingerprint(root, workspaceId);

it("retains an exclusive zero-byte claim across module reloads without resetting task identity", async () => {
  const taskId = "local-claim-test";
  localAccess.claimTask(taskId);
  const directory = path.join(state, "async-tasks"), name = createHash("sha256").update(taskId).digest("hex");
  expect(fs.readdirSync(directory)).toEqual([name]);
  const file = path.join(directory, name);
  expect(fs.statSync(file).size).toBe(0);
  expect(fs.statSync(file).mode & 0o777).toBe(0o600);
  expect(() => localAccess.claimTask(taskId)).toThrow("ASYNC_RESUME_UNSUPPORTED");
  vi.resetModules();
  const reloaded = await import("../../src/c2c/local.js");
  expect(() => reloaded.localAccess.claimTask(taskId)).toThrow("ASYNC_RESUME_UNSUPPORTED");
  expect(fs.readFileSync(file).length).toBe(0);
});

it.each(["tracked bytes", "index", "untracked bytes", "new untracked file", "deletion", "HEAD"])(
  "detects source drift in %s with no browser or transcript dependency", change => {
    const tracked = path.join(root, "hello.txt"), untracked = path.join(root, "new.txt");
    fs.writeFileSync(tracked, "dirty one\n"); fs.writeFileSync(untracked, "untracked one\n");
    const before = fingerprint();
    expect(fingerprint()).toBe(before);
    if (change === "tracked bytes") fs.writeFileSync(tracked, "dirty two\n");
    if (change === "index") git(root, "add", "hello.txt");
    if (change === "untracked bytes") fs.writeFileSync(untracked, "untracked two\n");
    if (change === "new untracked file") fs.writeFileSync(path.join(root, "extra.ts"), "export const extra = 1;\n");
    if (change === "deletion") fs.unlinkSync(tracked);
    if (change === "HEAD") git(root, "commit", "--allow-empty", "-m", "fixture revision");
    expect(fingerprint()).not.toBe(before);
  });

it("excludes ignored generated bytes from the source fingerprint", () => {
  fs.writeFileSync(path.join(root, ".gitignore"), "generated/\n");
  const generated = path.join(root, "generated"); fs.mkdirSync(generated);
  fs.writeFileSync(path.join(generated, "output.js"), "old build\n");
  const before = fingerprint();
  fs.writeFileSync(path.join(generated, "output.js"), "new build\n");
  expect(fingerprint()).toBe(before);
});

it("detects sensitive-file metadata drift without reading its contents", () => {
  const sensitive = path.join(root, ".npmrc"); fs.writeFileSync(sensitive, "engine-strict=true\n");
  const metadata = fs.statSync(sensitive), read = fs.readFileSync;
  vi.spyOn(fs, "readFileSync").mockImplementation((file, ...args) => {
    if (String(file) === sensitive) throw new Error("Sensitive content must not be read");
    return read(file, ...args);
  });
  const before = fingerprint();
  expect(fingerprint()).toBe(before);
  fs.writeFileSync(sensitive, "engine-strict=nope\n"); fs.utimesSync(sensitive, metadata.atime, metadata.mtime);
  expect(fingerprint()).not.toBe(before);
});

it("rejects an incorrect canonical workspace identity and unavailable source", () => {
  expect(() => localAccess.sourceFingerprint(root, "abcdef012345")).toThrow("ASYNC_SOURCE_WORKSPACE_MISMATCH");
  cleanup(root);
  expect(fingerprint).toThrow();
});
